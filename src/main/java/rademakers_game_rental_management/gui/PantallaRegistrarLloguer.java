    private void jBtnSeleccionarJocActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnSeleccionarJocActionPerformed
        String nomJoc = (String)jComboBoxJocs.getSelectedItem();
        Joc j = LogicaNegoci.cercarJoc(nomJoc);
        
        Plataforma pf = null;
        if (jRadioBtnPS5.isSelected()) {
            pf = Plataforma.PS5;
        } else if (jRadioBtnXbox.isSelected()){
            pf = Plataforma.Xbox;
        } else if (jRadioBtnPC.isSelected()){
            pf = Plataforma.PC;
        } else if (jRadioBtnSwitch2.isSelected()){
            pf = Plataforma.Switch2;
        } else if (pf == null) {
            JOptionPane.showMessageDialog(this, "Selecciona una plataforma.", "Error", JOptionPane.WARNING_MESSAGE);
            return;
        }
    }//GEN-LAST:event_jBtnSeleccionarJocActionPerformed

