    private void jBtnAltaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnAltaActionPerformed
        //Guarda l'usuari nou
        String nom = jTextFieldNomUsuari.getText();
        String llinatge1 = jTextFieldLlinatge1.getText();
        String llinatge2 = jTextFieldLlinatge2.getText();
        String dni = jTextFieldDNI.getText();
        String telefon = jTextFieldTelefon.getText();
        String dataAlta = jLblDataActual.getText();

        Usuari usuari = new Usuari(nom, llinatge1, llinatge2, dni, telefon, dataAlta);

        if (LogicaNegoci.afegirUsuari(usuari)) { 
            dispose(); // Tanca la finestra del registre.
        }else {
            JOptionPane.showMessageDialog(this, "Ja existeix un usuari amb aquest DNI.");
        }    
    }//GEN-LAST:event_jBtnAltaActionPerformed

